/**
 * One icon family, one stroke: the Feather set (MIT, https://feathericons.com),
 * 24 px grid, 2 px round strokes. Icons are decorative (`aria-hidden`); the control around them
 * carries the name.
 */
function icon(children: ReactNode) {
  return function Icon({ size = 20, ...props }: SVGProps<SVGSVGElement> & { size?: number }) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
        {...props}
      >
        {children}
      </svg>
    );
  };
}

